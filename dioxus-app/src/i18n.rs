pub struct T<'a> {
    dict: &'a Dict,
}

impl<'a> T<'a> {
    pub fn new(lang: Lang) -> Self {
        let dict = match lang {
            Lang::En => &EN,
            Lang::Zh => &ZH,
        };
        T { dict }
    }

    pub fn get(&self, key: &str) -> &'static str {
        for (k, v) in self.dict.iter() {
            if *k == key {
                return v;
            }
        }
        for (k, v) in EN.iter() {
            if *k == key {
                return v;
            }
        }
        "?"
    }

    pub fn f(&self, key: &str, params: &[(&str, String)]) -> String {
        let mut s = self.get(key).to_string();
        for (k, v) in params {
            s = s.replace(&format!("{{{k}}}"), v);
        }
        s
    }
}